const VALID_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp']);

function sanitizeFilename(filename) {
  return filename
    .replace(/[^a-zA-Z0-9.\-_]/g, '_')
    .replace(/_+/g, '_');
}

function processFolder(category) {
  const sourceFolder = path.join(REFERENCE_DIR, category.folderName);
  const targetFolder = path.join(PUBLIC_TARGET_DIR, category.id);

  if (!fs.existsSync(sourceFolder)) {
    console.warn(`[WARN] Folder not found: ${sourceFolder}`);
    return { ...category, items: [] };
  }

  if (!fs.existsSync(targetFolder)) {
    fs.mkdirSync(targetFolder, { recursive: true });
  }

  const files = fs.readdirSync(sourceFolder);
  const items = [];

  let copiedCount = 0;
  for (let i = 0; i < files.length; i++) {
    const file = files[i];
    const ext = path.extname(file).toLowerCase();

    if (!VALID_EXTENSIONS.has(ext)) {
      continue;
    }

    const cleanName = `${category.id}_${i + 1}${ext}`;
    const srcPath = path.join(sourceFolder, file);
    const destPath = path.join(targetFolder, cleanName);

    // Copy file if it doesn't exist or size is different
    const srcStat = fs.statSync(srcPath);
    let shouldCopy = true;
    if (fs.existsSync(destPath)) {
      const destStat = fs.statSync(destPath);
      if (destStat.size === srcStat.size) {
        shouldCopy = false;
      }
    }

    if (shouldCopy) {
      fs.copyFileSync(srcPath, destPath);
      copiedCount++;
    }

    items.push({
      id: `${category.id}-${i + 1}`,
      originalName: file,
      src: `/assets/references/${category.id}/${cleanName}`,
      category: category.id,
    });
  }

  console.log(`[OK] Category '${category.title.ar}': Total ${items.length} items (${copiedCount} copied).`);
  return {
    ...category,
    count: items.length,
    items,
  };
}

function main() {
  console.log('Generating reference images dataset...');
  if (!fs.existsSync(PUBLIC_TARGET_DIR)) {
    fs.mkdirSync(PUBLIC_TARGET_DIR, { recursive: true });
  }

  const processedCategories = CATEGORIES.map(processFolder);

  const totalPhotos = processedCategories.reduce((acc, cat) => acc + cat.items.length, 0);

  const fileContent = `// Auto-generated by scripts/generate-references-data.js
import type { LocalizedText } from "@/types";

export interface ReferenceImage {
  id: string;
  originalName: string;
  src: string;
  category: string;
}

export interface ReferenceCategory {
  id: string;
  folderName: string;
  title: LocalizedText;
  description: LocalizedText;
  badgeColor: string;
  count: number;
  items: ReferenceImage[];
}

export const referenceCategories: ReferenceCategory[] = ${JSON.stringify(processedCategories, null, 2)};

export const totalReferencePhotos = ${totalPhotos};
`;

  fs.writeFileSync(OUTPUT_JSON_FILE, fileContent, 'utf-8');
  console.log(`Successfully generated ${OUTPUT_JSON_FILE} with ${totalPhotos} total photos across ${processedCategories.length} categories.`);
}

main();
